"""Generate research/INDEX.md from the idea and decision records.

Usage: uv run python scripts/build_index.py [root]

Reads the front matter of research/ideas and research/decisions, the dated
headings of research/lessons.md and research/explore-runs/<idea>/*.md. The
output holds no timestamps of its own, so the same records give the same file.
"""

import importlib.util
import re
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("validate_records", _HERE / "validate_records.py")
_vr = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_vr)

REPO = _vr.REPO
SKIP = _vr.SKIP
read_front_matter = _vr.read_front_matter

LESSON = re.compile(r"^## (\d{4}-\d{2}-\d{2}): (.+)$")
LESSON_LIMIT = 10

HEADER = """# Research index

Generated by `uv run python scripts/build_index.py`. Do not edit by hand.
"""


def cell(value: object) -> str:
    """Make a value safe for a Markdown table cell."""
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def slug(heading: str) -> str:
    """GitHub-style anchor: lowercase, drop punctuation except - and space."""
    return re.sub(r"[^\w\- ]", "", heading.lower()).replace(" ", "-")


def records(root: Path, folder: str) -> list[tuple[str, Path, dict]]:
    """(id, path, front matter) for each parseable record, sorted by id then name."""
    d = root / "research" / folder
    out: list[tuple[str, Path, dict]] = []
    if not d.is_dir():
        return out
    for path in d.glob("*.md"):
        if path.name in SKIP:
            continue
        fm = read_front_matter(path)
        if isinstance(fm, str):
            continue
        out.append((str(fm.get("id", path.name[:4])), path, fm))
    return sorted(out, key=lambda r: (r[0], r[1].name))


def link(root: Path, path: Path, title: object) -> str:
    rel = path.relative_to(root / "research").as_posix()
    return f"[{cell(title)}]({rel})"


def ideas_table(root: Path) -> str:
    lines = [
        "| id | title | status | updated | datasets |",
        "| --- | --- | --- | --- | --- |",
    ]
    for rid, path, fm in records(root, "ideas"):
        ds = fm.get("datasets")
        datasets = ", ".join(str(x) for x in ds) if isinstance(ds, list) else ""
        lines.append(
            f"| {cell(rid)} | {link(root, path, fm.get('title', path.stem))} "
            f"| {cell(fm.get('status', ''))} | {cell(fm.get('updated', ''))} | {cell(datasets)} |"
        )
    return "\n".join(lines)


def decisions_table(root: Path) -> str:
    lines = ["| id | title | status | date |", "| --- | --- | --- | --- |"]
    for rid, path, fm in records(root, "decisions"):
        lines.append(
            f"| {cell(rid)} | {link(root, path, fm.get('title', path.stem))} "
            f"| {cell(fm.get('status', ''))} | {cell(fm.get('date', ''))} |"
        )
    return "\n".join(lines)


def lessons_list(root: Path) -> str:
    path = root / "research" / "lessons.md"
    found: list[tuple[str, str]] = []
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            m = LESSON.match(line.rstrip())
            if m:
                found.append((m.group(1), m.group(2).strip()))
    # Newest date first; the sort is stable, so file order holds within a date.
    found = sorted(found, key=lambda x: x[0], reverse=True)[:LESSON_LIMIT]
    lines = [f"- {date}: [{cell(title)}](lessons.md#{slug(title)})" for date, title in found]
    return "\n".join(lines) if lines else "None yet."


def explore_runs(root: Path) -> str:
    base = root / "research" / "explore-runs"
    lines = ["| idea | runs | newest |", "| --- | --- | --- |"]
    if base.is_dir():
        for folder in sorted(p for p in base.iterdir() if p.is_dir()):
            runs = [p for p in folder.glob("*.md") if p.name not in SKIP]
            if not runs:
                continue
            numeric = [p for p in runs if p.stem.isdigit()]
            newest = max(numeric, key=lambda p: int(p.stem)) if numeric else max(runs)
            rel = newest.relative_to(root / "research").as_posix()
            lines.append(f"| {cell(folder.name)} | {len(runs)} | [{cell(newest.stem)}]({rel}) |")
    return "\n".join(lines)


def build(root: Path = REPO) -> str:
    parts = [
        HEADER,
        "## Ideas\n\n" + ideas_table(root),
        "## Decisions\n\n" + decisions_table(root),
        f"## Newest lessons\n\n{lessons_list(root)}",
        "## Explore runs\n\n" + explore_runs(root),
    ]
    return "\n".join(p.rstrip("\n") + "\n" for p in parts)


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    root = Path(args[0]) if args else REPO
    text = build(root)
    out = root / "research" / "INDEX.md"
    with out.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
