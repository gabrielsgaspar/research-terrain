"""Generate research/INDEX.md from the idea and decision records.

Usage: python3 scripts/build_index.py [--stdout] [root]

The index is not in git: it is built where it is read (the planner and
reviewer workflows build it before the agent starts; locally, run the line
above). This script uses the standard library only, so it runs with any
Python 3.10 or later, the runner's own `python3 -I` included, without the
project environment.

Reads the front matter of research/ideas and research/decisions, the newest
`## Status` line of each dead or parked idea, the dated headings of
research/lessons.md and research/explore-runs/<idea>/*.md. The output holds
no timestamps of its own, so the same records give the same file.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SKIP = {"README.md", "TEMPLATE.md"}

LESSON = re.compile(r"^## (\d{4}-\d{2}-\d{2}): (.+)$")
LESSON_LIMIT = 10
DATED = re.compile(r"^(\d{4}-\d{2}-\d{2})\b")
ENDED = ("dead", "parked")  # idea statuses whose newest Status line the index shows

HEADER = """# Research index

Generated by `python3 scripts/build_index.py`. Not in git; do not edit by hand.
"""


def _scalar(text: str) -> object:
    """A YAML scalar as the index needs it: quoted or plain string, inline list or null."""
    text = text.strip()
    if text in ("", "null", "~"):
        return None
    if text.startswith("[") and text.endswith("]"):
        inner = text[1:-1].strip()
        if not inner:
            return []
        items = re.findall(r'"(?:[^"\\]|\\.)*"|\'(?:[^\']|\'\')*\'|[^,]+', inner)
        return [_scalar(i) for i in items if i.strip()]
    if len(text) >= 2 and text[0] == text[-1] == '"':
        return re.sub(r"\\(.)", r"\1", text[1:-1])
    if len(text) >= 2 and text[0] == text[-1] == "'":
        return text[1:-1].replace("''", "'")
    return text


def parse_front_matter(text: str) -> dict | None:
    """The top-level keys of a record's front matter, or None if it has none.

    Handles what the records use: `key: scalar`, `key: [inline, list]` and
    `key:` followed by `  - item` lines. Dates stay strings. Nested mappings
    are skipped; the index reads none.
    """
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        return None
    out: dict = {}
    key = None
    for line in lines[1:end]:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line[0] not in " \t-":
            name, sep, rest = line.partition(":")
            if not sep:
                return None
            key = name.strip()
            out[key] = _scalar(rest)
        elif line.lstrip().startswith("- ") and key is not None:
            if not isinstance(out.get(key), list):
                out[key] = []
            out[key].append(_scalar(line.lstrip()[2:]))
    return out


def newest_status_line(text: str) -> str:
    """The newest dated item under `## Status`, on one line ("" if there is none).

    Items are `- ` bullets, possibly wrapped over several lines. The newest
    is the one with the latest date; of several on that date, the last.
    """
    items: list[str] = []
    inside = False
    for line in text.splitlines():
        if line.startswith("## "):
            inside = line.strip() == "## Status"
            continue
        if not inside:
            continue
        if line.startswith("- "):
            items.append(line[2:].strip())
        elif line.strip() and items and line[:1] in (" ", "\t"):
            items[-1] += " " + line.strip()
    best, best_date = "", ""
    for item in items:
        m = DATED.match(item)
        date = m.group(1) if m else ""
        if date >= best_date:
            best, best_date = item, date
    return best


def cell(value: object) -> str:
    """Make a value safe for a Markdown table cell."""
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def slug(heading: str) -> str:
    """GitHub-style anchor: lowercase, drop punctuation except - and space."""
    return re.sub(r"[^\w\- ]", "", heading.lower()).replace(" ", "-")


def records(root: Path, folder: str) -> list[tuple[str, Path, dict]]:
    """(id, path, front matter) for each parseable record, sorted by id then name."""
    d = root / "research" / folder
    out: list[tuple[str, Path, dict]] = []
    if not d.is_dir():
        return out
    for path in d.glob("*.md"):
        if path.name in SKIP:
            continue
        fm = parse_front_matter(path.read_text(encoding="utf-8"))
        if fm is None:
            continue
        out.append((str(fm.get("id") or path.name[:4]), path, fm))
    return sorted(out, key=lambda r: (r[0], r[1].name))


def link(root: Path, path: Path, title: object) -> str:
    rel = path.relative_to(root / "research").as_posix()
    return f"[{cell(title)}]({rel})"


def ideas_table(root: Path) -> str:
    lines = [
        "| id | title | status | updated | datasets |",
        "| --- | --- | --- | --- | --- |",
    ]
    for rid, path, fm in records(root, "ideas"):
        ds = fm.get("datasets")
        datasets = ", ".join(str(x) for x in ds) if isinstance(ds, list) else ""
        lines.append(
            f"| {cell(rid)} | {link(root, path, fm.get('title') or path.stem)} "
            f"| {cell(fm.get('status') or '')} | {cell(fm.get('updated') or '')} "
            f"| {cell(datasets)} |"
        )
    return "\n".join(lines)


def ended_ideas(root: Path) -> str:
    """For each dead or parked idea, the newest line of its Status log: why it ended."""
    lines = []
    for rid, path, fm in records(root, "ideas"):
        status = fm.get("status")
        if status not in ENDED:
            continue
        why = newest_status_line(path.read_text(encoding="utf-8")) or "No Status line."
        lines.append(f"- {cell(rid)}, {status}: {cell(why)} ({link(root, path, 'idea file')})")
    return "\n".join(lines) if lines else "None."


def decisions_table(root: Path) -> str:
    lines = ["| id | title | status | date |", "| --- | --- | --- | --- |"]
    for rid, path, fm in records(root, "decisions"):
        lines.append(
            f"| {cell(rid)} | {link(root, path, fm.get('title') or path.stem)} "
            f"| {cell(fm.get('status') or '')} | {cell(fm.get('date') or '')} |"
        )
    return "\n".join(lines)


def lessons_list(root: Path) -> str:
    path = root / "research" / "lessons.md"
    found: list[tuple[str, str]] = []
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            m = LESSON.match(line.rstrip())
            if m:
                found.append((m.group(1), m.group(2).strip()))
    # Newest date first; the sort is stable, so file order holds within a date.
    found = sorted(found, key=lambda x: x[0], reverse=True)[:LESSON_LIMIT]
    lines = [f"- {date}: [{cell(title)}](lessons.md#{slug(title)})" for date, title in found]
    return "\n".join(lines) if lines else "None yet."


def explore_runs(root: Path) -> str:
    base = root / "research" / "explore-runs"
    lines = ["| idea | runs | newest |", "| --- | --- | --- |"]
    if base.is_dir():
        for folder in sorted(p for p in base.iterdir() if p.is_dir()):
            runs = [p for p in folder.glob("*.md") if p.name not in SKIP]
            if not runs:
                continue
            numeric = [p for p in runs if p.stem.isdigit()]
            newest = max(numeric, key=lambda p: int(p.stem)) if numeric else max(runs)
            rel = newest.relative_to(root / "research").as_posix()
            lines.append(f"| {cell(folder.name)} | {len(runs)} | [{cell(newest.stem)}]({rel}) |")
    return "\n".join(lines)


def build(root: Path = REPO) -> str:
    parts = [
        HEADER,
        "## Ideas\n\n" + ideas_table(root),
        "## Why dead and parked ideas ended\n\n"
        "The newest line of each one's Status log.\n\n" + ended_ideas(root),
        "## Decisions\n\n" + decisions_table(root),
        f"## Newest lessons\n\n{lessons_list(root)}",
        "## Explore runs\n\n" + explore_runs(root),
    ]
    return "\n".join(p.rstrip("\n") + "\n" for p in parts)


def main(argv: list[str] | None = None) -> int:
    """Write <root>/research/INDEX.md; with --stdout, print it instead."""
    args = sys.argv[1:] if argv is None else argv
    to_stdout = "--stdout" in args
    paths = [a for a in args if a != "--stdout"]
    root = Path(paths[0]) if paths else REPO
    text = build(root)
    if to_stdout:
        sys.stdout.buffer.write(text.encode("utf-8"))
        return 0
    out = root / "research" / "INDEX.md"
    with out.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
