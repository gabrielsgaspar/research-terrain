"""Sync the curated Zotero library into `refs.bib` and reference-note stubs.

Pure functions: the network is an injected `get(url, headers) -> (headers, body)`
callable, so tests need no network. The key is only ever sent in a header.
"""

from __future__ import annotations

import json
import re
from collections.abc import Callable
from pathlib import Path
from urllib.parse import urlunsplit

API_HOST = "api.zotero.org"
SKIP_TYPES = {"attachment", "note", "annotation"}
KEY_RE = re.compile(r"^[A-Za-z0-9_:\-.]+$")
_EXTRA_RE = re.compile(r"(?im)^\s*citation key:\s*(\S.*?)\s*$")
ROLES = ("closest", "adjacent", "method")
BIB_HEADER = "% Generated by scripts/zotero_sync.py from the Zotero library; do not edit."

STUB_HEADINGS = """\
## Question            <!-- agent-drafted, confirm -->
## Setting and data    <!-- agent-drafted, confirm -->
## Identification      <!-- agent-drafted, confirm -->
## Main result         <!-- agent-drafted, confirm; include magnitudes -->
## What it doesn't do  <!-- Gabriel -->
## Relevance to us     <!-- Gabriel: what we borrow, how we differ -->
"""

STUB_TEMPLATE = (
    """\
---
citekey: {citekey}
doi: {doi}
zotero_key: {zotero_key}
status: core
role: {role}
strands: []
links: []
---
"""
    + STUB_HEADINGS
)

Get = Callable[[str, dict[str, str]], tuple[dict[str, str], bytes]]


def fetch_items(get: Get, group: str, key: str) -> list[dict]:
    """Page through the group's top-level items."""
    headers = {"Zotero-API-Key": key, "Zotero-API-Version": "3"}
    items: list[dict] = []
    start = 0
    while True:
        url = urlunsplit(
            (
                "https",
                API_HOST,
                f"/groups/{group}/items/top",
                f"format=json&include=data,bibtex&limit=100&start={start}",
                "",
            )
        )
        resp_headers, body = get(url, headers)
        page = json.loads(body.decode("utf-8"))
        if not page:
            break
        items.extend(page)
        start += len(page)
        lowered = {k.lower(): v for k, v in resp_headers.items()}
        total = int(lowered.get("total-results", "0"))
        if start >= total:
            break
    return items


def citation_key(item: dict) -> str | None:
    """The pinned Better BibTeX key, or None if the item has none."""
    data = item.get("data", {})
    key = (data.get("citationKey") or "").strip()
    if not key:
        match = _EXTRA_RE.search(data.get("extra") or "")
        key = match.group(1) if match else ""
    if not key:
        return None
    if not KEY_RE.match(key):
        raise ValueError(f"invalid citation key: {key!r}")
    return key


def _keyed(items: list[dict]) -> list[tuple[str, dict]]:
    out = []
    for item in items:
        if item.get("data", {}).get("itemType") in SKIP_TYPES:
            continue
        key = citation_key(item)
        if key is not None:
            out.append((key, item))
    return out


def render_bib(items: list[dict]) -> str:
    """Deterministic refs.bib text for every keyed item."""
    entries: dict[str, str] = {}
    for key, item in _keyed(items):
        if key in entries:
            raise ValueError(f"duplicate citation key: {key}")
        bib = (item.get("bibtex") or "").replace("\r\n", "\n").strip()
        start = bib.find("{")
        comma = bib.find(",")
        if start == -1 or comma == -1 or comma < start:
            raise ValueError(f"malformed BibTeX entry for key {key}")
        entries[key] = bib[: start + 1] + key + bib[comma:]
    body = "\n\n".join(entries[k] for k in sorted(entries))
    return BIB_HEADER + ("\n\n" + body if body else "") + "\n"


def stub(item: dict) -> str:
    """Note stub for one keyed item (BUILD_PLAN section 4.2)."""
    data = item.get("data", {})
    tags = {t.get("tag") for t in data.get("tags", [])}
    role = next((r for r in ROLES if r in tags), "")
    key = citation_key(item) or ""
    return STUB_TEMPLATE.format(
        citekey=key,
        doi=data.get("DOI") or "",
        zotero_key=item.get("key", ""),
        role=role,
    ).replace(": \n", ":\n")


def sync(items: list[dict], references_dir: Path) -> dict:
    """Write refs.bib and missing stubs; return the report."""
    references_dir = Path(references_dir)
    keyed = _keyed(items)
    candidates = [i for i in items if i.get("data", {}).get("itemType") not in SKIP_TYPES]
    unkeyed = [
        {"zotero_key": i.get("key", ""), "title": i.get("data", {}).get("title", "")}
        for i in candidates
        if citation_key(i) is None
    ]
    bib = render_bib(items)
    references_dir.mkdir(parents=True, exist_ok=True)
    with (references_dir / "refs.bib").open("w", encoding="utf-8", newline="\n") as f:
        f.write(bib)
    written = []
    for key, item in keyed:
        tags = {t.get("tag") for t in item.get("data", {}).get("tags", [])}
        path = references_dir / f"{key}.md"
        if "core" in tags and not path.exists():
            with path.open("w", encoding="utf-8", newline="\n") as f:
                f.write(stub(item))
            written.append(key)
    return {
        "items_read": len(items),
        "keyed": len(keyed),
        "unkeyed": unkeyed,
        "bib_entries": len(keyed),
        "stubs_written": sorted(written),
    }
