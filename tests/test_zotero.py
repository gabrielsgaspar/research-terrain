import json
import random

import pytest

from terrain.zotero import citation_key, fetch_items, render_bib, stub, sync

SECRET = "sekret-read-key"


def make_item(n, **data):
    base = {
        "itemType": "journalArticle",
        "title": f"Title {n}",
        "DOI": f"10.1/{n}",
        "tags": [],
        "extra": "",
        "citationKey": f"key{n:03d}",
    }
    base.update(data)
    return {
        "key": f"ZK{n:04d}",
        "data": base,
        "bibtex": f"@article{{zot{n},\r\n  title = {{T{n}}}\r\n}}  \r\n",
    }


def test_fetch_pages_and_key_only_in_header():
    all_items = [make_item(i) for i in range(230)]
    calls = []

    def get(url, headers):
        calls.append((url, headers))
        start = int(url.split("start=")[1])
        page = all_items[start : start + 100]
        return {"total-results": "230"}, json.dumps(page).encode("utf-8")

    got = fetch_items(get, "123", SECRET)
    assert len(got) == 230
    assert [int(u.split("start=")[1]) for u, _ in calls] == [0, 100, 200]
    for url, headers in calls:
        assert SECRET not in url
        assert headers["Zotero-API-Key"] == SECRET
        assert headers["Zotero-API-Version"] == "3"


def test_citation_key_rules():
    assert citation_key({"data": {"citationKey": "a", "extra": "Citation Key: b"}}) == "a"
    assert citation_key({"data": {"citationKey": " ", "extra": "x\nCITATION key:  b2 \n"}}) == "b2"
    assert citation_key({"data": {"extra": "nothing"}}) is None
    assert citation_key({"data": {}}) is None
    with pytest.raises(ValueError):
        citation_key({"data": {"citationKey": "a b"}})
    with pytest.raises(ValueError):
        citation_key({"data": {"citationKey": "a{b"}})


def test_render_bib_sorted_deterministic_and_keys_replaced():
    items = [make_item(i) for i in range(5)]
    text = render_bib(items)
    assert text.startswith(
        "% Generated by scripts/zotero_sync.py from the Zotero library; do not edit.\n\n"
    )
    assert "@article{key000," in text and "zot0" not in text
    assert "\r" not in text and text.endswith("}\n") and not text.endswith("\n\n")
    positions = [text.index(f"@article{{key{i:03d},") for i in range(5)]
    assert positions == sorted(positions)
    shuffled = items[:]
    random.Random(1).shuffle(shuffled)
    assert render_bib(shuffled).encode("utf-8") == text.encode("utf-8")


def test_render_bib_duplicate_raises():
    with pytest.raises(ValueError, match="dup"):
        render_bib([make_item(1, citationKey="same"), make_item(2, citationKey="same")])


def test_sync_stubs_skips_and_report(tmp_path):
    core = make_item(1, tags=[{"tag": "core"}, {"tag": "adjacent"}, {"tag": "method"}])
    existing = make_item(2, tags=[{"tag": "core"}])
    plain = make_item(3, tags=[{"tag": "read"}])
    attach = make_item(4, itemType="attachment")
    note = make_item(5, itemType="note")
    unkeyed = make_item(6, citationKey="", title="No key")
    note_path = tmp_path / "key002.md"
    note_path.write_bytes(b"mine\n")

    report = sync([core, existing, plain, attach, note, unkeyed], tmp_path)

    assert report == {
        "items_read": 6,
        "keyed": 3,
        "unkeyed": [{"zotero_key": "ZK0006", "title": "No key"}],
        "bib_entries": 3,
        "stubs_written": ["key001"],
    }
    assert note_path.read_bytes() == b"mine\n"
    assert not (tmp_path / "key003.md").exists()
    text = (tmp_path / "key001.md").read_text(encoding="utf-8")
    assert text == stub(core)
    assert text.startswith(
        "---\ncitekey: key001\ndoi: 10.1/1\nzotero_key: ZK0001\nstatus: core\n"
        "role: adjacent\nstrands: []\nlinks: []\n---\n"
    )
    assert text.count("\n## ") == 6 and text.count("<!--") == 6
    bib = (tmp_path / "refs.bib").read_text(encoding="utf-8")
    assert "key006" not in bib and "key004" not in bib and "key005" not in bib
    assert "key001" in bib
